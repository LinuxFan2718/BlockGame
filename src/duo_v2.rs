//! v2 network inputs, policy indices and board symmetries.
//!
//! Every plane is derived from the rules (who owns a cell, where a player may
//! attach or never play, which cells its legal moves can reach). There are no
//! strategy heuristics. Positions are seen from the mover's frame: player 1 sees
//! the board rotated 180°, as in v1, so a policy index is an action id in that frame.
use crate::duo::{self, Bits, CELLS, Game, PASS, PIECES, SIZE};
use std::collections::HashMap;
use std::sync::OnceLock;

/// own, opponent, own attach, opponent attach, own forbidden, opponent forbidden,
/// own reachable, opponent reachable, on-board.
pub const PLANES: usize = 9;
/// Inventories (2 × 21), two scores, consecutive passes, first-player flag and
/// two log-mobility counts.
pub const SCALARS: usize = 2 * PIECES + 6;
pub const POLICY_SIZE: usize = PASS + 1;
/// Identity, 180° rotation, main-diagonal and anti-diagonal reflections: the
/// square symmetries that map the start-square set {(4,4), (9,9)} to itself.
pub const SYMMETRIES: usize = 4;

pub fn frame_cell(player: usize, cell: usize) -> usize {
    if player == 0 { cell } else { CELLS - 1 - cell }
}

pub fn sym_cell(sym: usize, cell: usize) -> usize {
    let (r, c) = (cell / SIZE, cell % SIZE);
    let last = SIZE - 1;
    let (r, c) = match sym {
        0 => (r, c),
        1 => (last - r, last - c),
        2 => (c, r),
        3 => (last - c, last - r),
        _ => panic!("unknown symmetry"),
    };
    r * SIZE + c
}

struct Tables {
    /// [player][action] -> policy index in that player's frame.
    framed: [Vec<u16>; 2],
    /// [sym][policy index] -> policy index after the symmetry.
    symmetric: [Vec<u16>; SYMMETRIES],
}

fn tables() -> &'static Tables {
    static TABLES: OnceLock<Tables> = OnceLock::new();
    TABLES.get_or_init(|| {
        let mut by_cells = HashMap::new();
        for action in 0..PASS {
            if let Some(p) = duo::placement(action) {
                by_cells.insert(p.cells.clone(), action);
            }
        }
        let lookup = |cells: &[usize], map: &dyn Fn(usize) -> usize| {
            let mut moved: Vec<_> = cells.iter().map(|&c| map(c)).collect();
            moved.sort_unstable();
            by_cells[&moved] as u16
        };
        let mut framed = [vec![u16::MAX; POLICY_SIZE], vec![u16::MAX; POLICY_SIZE]];
        let mut symmetric: [Vec<u16>; SYMMETRIES] =
            std::array::from_fn(|_| vec![u16::MAX; POLICY_SIZE]);
        for action in 0..PASS {
            let Some(p) = duo::placement(action) else {
                continue;
            };
            for (player, table) in framed.iter_mut().enumerate() {
                table[action] = lookup(&p.cells, &|c| frame_cell(player, c));
            }
            for (sym, table) in symmetric.iter_mut().enumerate() {
                table[action] = lookup(&p.cells, &|c| sym_cell(sym, c));
            }
        }
        for table in framed.iter_mut().chain(symmetric.iter_mut()) {
            table[PASS] = PASS as u16;
        }
        Tables { framed, symmetric }
    })
}

/// Policy index of `action` for `player` after symmetry `sym`.
pub fn policy_index(action: usize, player: usize, sym: usize) -> u16 {
    let t = tables();
    t.symmetric[sym][t.framed[player][action] as usize]
}

/// For symmetry `sym`: where each cell goes, and where each policy index goes.
pub fn symmetry_tables(sym: usize) -> (Vec<u16>, Vec<u16>) {
    let cells = (0..CELLS).map(|c| sym_cell(sym, c) as u16).collect();
    let policy = tables().symmetric[sym].clone();
    (cells, policy)
}

fn mobility(count: usize) -> f32 {
    ((1 + count) as f32).ln() / 7.0
}

/// Writes one position for the player to move. `actions` is that player's legal
/// list (as generated by the engine); `legal` receives their policy indices.
/// Returns the opponent's reachable-cell count for diagnostics.
pub fn encode(
    game: &Game,
    actions: &[usize],
    sym: usize,
    planes: &mut [u8],
    scalars: &mut [f32],
    legal: &mut Vec<u16>,
) {
    assert_eq!(planes.len(), PLANES * CELLS);
    assert_eq!(scalars.len(), SCALARS);
    let me = game.turn();
    let them = 1 - me;
    let mut my_reach = Bits::default();
    let mut my_moves = 0;
    for &action in actions {
        if let Some(p) = duo::placement(action) {
            my_reach = my_reach.union(p.mask);
            my_moves += 1;
        }
    }
    let (their_reach, their_moves) = game.reach_for(them);
    let sets = [
        game.owned_cells(me),
        game.owned_cells(them),
        game.attach_cells(me),
        game.attach_cells(them),
        game.forbidden_cells(me),
        game.forbidden_cells(them),
        my_reach,
        their_reach,
    ];
    planes.fill(0);
    let destination: [usize; CELLS] = std::array::from_fn(|c| sym_cell(sym, frame_cell(me, c)));
    for (plane, bits) in sets.iter().enumerate() {
        for cell in bits.cells() {
            planes[plane * CELLS + destination[cell]] = 1;
        }
    }
    planes[8 * CELLS..].fill(1);
    let (mine, theirs) = (game.remaining_mask(me), game.remaining_mask(them));
    for piece in 0..PIECES {
        scalars[piece] = f32::from(mine & (1 << piece) != 0);
        scalars[PIECES + piece] = f32::from(theirs & (1 << piece) != 0);
    }
    let scores = game.scores();
    let base = 2 * PIECES;
    scalars[base] = f32::from(scores[me] + 89) / 109.0;
    scalars[base + 1] = f32::from(scores[them] + 89) / 109.0;
    scalars[base + 2] = f32::from(game.consecutive_passes()) / 2.0;
    scalars[base + 3] = f32::from(me == 0);
    scalars[base + 4] = mobility(my_moves);
    scalars[base + 5] = mobility(their_moves);
    legal.clear();
    legal.extend(actions.iter().map(|&a| policy_index(a, me, sym)));
}

/// Final ownership of every cell from `player`'s view, in its frame after `sym`:
/// 0 empty, 1 own, 2 opponent.
pub fn ownership(final_board: &[u8; CELLS], player: usize, sym: usize, out: &mut [u8]) {
    for (cell, &color) in final_board.iter().enumerate() {
        let value = match color {
            0 => 0,
            c if usize::from(c) == player + 1 => 1,
            _ => 2,
        };
        out[sym_cell(sym, frame_cell(player, cell))] = value;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn random_positions(count: usize, seed: u64) -> Vec<Game> {
        let mut state = seed;
        let mut out = Vec::new();
        while out.len() < count {
            let mut game = Game::new();
            while !game.is_terminal() {
                out.push(game.clone());
                let actions = game.legal_actions();
                state = state
                    .wrapping_mul(6364136223846793005)
                    .wrapping_add(1442695040888963407);
                game.step(actions[(state >> 33) as usize % actions.len()])
                    .unwrap();
            }
        }
        out
    }

    #[test]
    fn symmetry_tables_are_permutations_matching_cell_geometry() {
        for sym in 0..SYMMETRIES {
            let mut seen = vec![false; POLICY_SIZE];
            for action in 0..POLICY_SIZE {
                if action != PASS && duo::placement(action).is_none() {
                    continue; // Ids whose shape does not fit at that anchor.
                }
                let index = tables().symmetric[sym][action] as usize;
                assert!(!seen[index], "sym {sym} not injective");
                seen[index] = true;
                if let Some(p) = duo::placement(action) {
                    let q = duo::placement(index).unwrap();
                    let mut moved: Vec<_> = p.cells.iter().map(|&c| sym_cell(sym, c)).collect();
                    moved.sort_unstable();
                    assert_eq!(moved, q.cells);
                    assert_eq!(p.piece, q.piece);
                }
            }
            // Every symmetry maps the start-square set to itself.
            let mut starts: Vec<_> = duo::STARTS.iter().map(|&c| sym_cell(sym, c)).collect();
            starts.sort_unstable();
            assert_eq!(starts, duo::STARTS.to_vec());
        }
    }

    #[test]
    fn symmetric_encodings_are_consistent() {
        // Under a symmetry, every plane moves cell-for-cell and every legal move
        // maps to the transformed move covering the transformed cells.
        let (mut base, mut moved) = (vec![0; PLANES * CELLS], vec![0; PLANES * CELLS]);
        let (mut s0, mut s1) = (vec![0.0; SCALARS], vec![0.0; SCALARS]);
        let (mut l0, mut l1) = (Vec::new(), Vec::new());
        for game in random_positions(400, 7) {
            let actions = game.legal_actions();
            encode(&game, &actions, 0, &mut base, &mut s0, &mut l0);
            for sym in 1..SYMMETRIES {
                encode(&game, &actions, sym, &mut moved, &mut s1, &mut l1);
                assert_eq!(s0, s1);
                for plane in 0..PLANES {
                    for cell in 0..CELLS {
                        assert_eq!(
                            base[plane * CELLS + cell],
                            moved[plane * CELLS + sym_cell(sym, cell)]
                        );
                    }
                }
                for (a, b) in l0.iter().zip(&l1) {
                    assert_eq!(tables().symmetric[sym][*a as usize], *b);
                }
            }
        }
    }

    #[test]
    fn planes_match_rule_definitions() {
        let mut planes = vec![0; PLANES * CELLS];
        let mut scalars = vec![0.0; SCALARS];
        let mut legal = Vec::new();
        for game in random_positions(300, 11) {
            let me = game.turn();
            let actions = game.legal_actions();
            encode(&game, &actions, 0, &mut planes, &mut scalars, &mut legal);
            let at = |plane: usize, cell: usize| planes[plane * CELLS + frame_cell(me, cell)];
            for cell in 0..CELLS {
                let owner = game.board()[cell];
                assert_eq!(at(0, cell), u8::from(owner == me as u8 + 1));
                assert_eq!(at(1, cell), u8::from(owner == 2 - me as u8));
                // Reachable: some legal placement covers it.
                let covered = actions
                    .iter()
                    .any(|&a| duo::placement(a).is_some_and(|p| p.cells.contains(&cell)));
                assert_eq!(at(6, cell), u8::from(covered));
                // Every legal placement touches an attach cell of the mover.
                if at(2, cell) == 1 {
                    assert_eq!(owner, 0);
                }
            }
            for &a in &actions {
                if let Some(p) = duo::placement(a) {
                    assert!(p.cells.iter().any(|&c| at(2, c) == 1));
                    assert!(
                        p.cells
                            .iter()
                            .all(|&c| at(4, c) == 0 && owner_free(&game, c))
                    );
                }
            }
            // Policy indices are action ids in the mover's frame.
            for (&a, &i) in actions.iter().zip(&legal) {
                if a == PASS {
                    assert_eq!(i as usize, PASS);
                    continue;
                }
                let p = duo::placement(a).unwrap();
                let mut framed: Vec<_> = p.cells.iter().map(|&c| frame_cell(me, c)).collect();
                framed.sort_unstable();
                assert_eq!(duo::placement(i as usize).unwrap().cells, framed);
            }
        }
    }

    fn owner_free(game: &Game, cell: usize) -> bool {
        game.board()[cell] == 0
    }
}
